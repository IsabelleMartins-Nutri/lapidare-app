--     por porção, usada pela busca do novo editor visual de plano
--     alimentar (digita o nome, os valores preenchem sozinhos).
--   - RLS: qualquer nutri autenticada pode LER todos os alimentos
--     (base global + de outras nutris), mas só edita os que ela mesma
--     cadastrar (nutri_id = seu próprio id). É a primeira tabela
--     "compartilhada" do app — todas as outras são só da própria nutri.
--   - Popula com a base TACO (Tabela Brasileira de Composição de
--     Alimentos, 4ª edição, NEPA/UNICAMP) — 372 alimentos com valores
--     por porção (medida caseira já convertida). Fonte enviada pela
--     Daniela (taco_alimentos.json).
--
-- Como rodar (30 seg):
--   1. Supabase → SQL Editor → + New query
--   2. Cola TUDO → Run
--   3. Esperado: "Success. No rows returned"
--
-- 100% seguro: idempotente (roda de novo sem duplicar nada; a base TACO
-- é substituída por completo, mas alimentos que você mesma cadastrar
-- depois ficam intactos).
-- ════════════════════════════════════════════════════════════════════

create table if not exists public.alimentos (
  id             uuid primary key default gen_random_uuid(),
  nutri_id       uuid references public.nutris(id) on delete cascade,
  nome           text not null,
  medida_padrao  text,
  kcal           numeric(7,1),
  prot_g         numeric(6,1),
  cho_g          numeric(6,1),
  lip_g          numeric(6,1),
  fibra_g        numeric(6,1),
  created_at     timestamptz not null default now()
);
create index if not exists alimentos_nome_idx on public.alimentos(lower(nome));
create index if not exists alimentos_nutri_id_idx on public.alimentos(nutri_id);

alter table public.alimentos enable row level security;

drop policy if exists alimentos_select on public.alimentos;
create policy alimentos_select on public.alimentos
  for select using (auth.uid() is not null);

drop policy if exists alimentos_write_nutri on public.alimentos;
create policy alimentos_write_nutri on public.alimentos
  for all using (nutri_id = auth.uid()) with check (nutri_id = auth.uid());

